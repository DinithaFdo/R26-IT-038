"use client";

import { FileText } from "lucide-react";
import type { TextXaiAuditResponse } from "@/types/api";

// ─── Heatmap tab content ──────────────────────────────────────────────────────

export function HeatmapTabContent({
  result,
}: {
  result: TextXaiAuditResponse;
}) {
  return (
    <div className="space-y-4">
      <div className="space-y-1">
        <h3 className="text-sm font-semibold">Token Attention Heatmap</h3>
        <p className="text-xs text-muted-foreground">
          Words are highlighted by how much they influenced the
          classification. Darker highlights had more influence on the result.
        </p>
      </div>

      <div className="leading-8 tracking-wide">
        {result.heatmap_data.map((tokenObj, index) => {
          if (tokenObj.is_noise) {
  // Hide [CLS] and [SEP] structural tokens completely
  if (tokenObj.display_token === "[CLS]" ||
      tokenObj.display_token === "[SEP]") {
    return null;
  }
  return (
    <span
      key={index}
      className="text-muted-foreground mr-1"
    >
      {tokenObj.display_token}
    </span>
  );
}

          const backgroundAlpha = tokenObj.normalized_score * 0.85;
          const textColor =
            tokenObj.normalized_score > 0.65 ? "#ffffff" : "#1f2937";

          return (
            <span
              key={index}
              className="px-1 mx-[1px] rounded transition-all duration-200 hover:scale-105 inline-block cursor-help relative group"
              style={{
                backgroundColor: `rgba(251, 191, 36, ${backgroundAlpha})`,
                color: textColor,
              }}
            >
              {tokenObj.display_token}

              {/* Hover tooltip */}
              <span className="absolute bottom-full left-1/2 transform -translate-x-1/2 mb-1 hidden group-hover:block bg-gray-900 text-white text-xs px-2 py-1 rounded shadow-lg whitespace-nowrap z-10 pointer-events-none opacity-90 transition-opacity">
                Impact: {(tokenObj.normalized_score * 100).toFixed(1)}%
              </span>
            </span>
          );
        })}
      </div>

      {/* Legend */}
      <div className="flex items-center gap-3 mt-4
                pt-3 border-t border-border">
  <span className="text-xs text-muted-foreground
                   flex-shrink-0">
    Low influence
  </span>
  <div
    className="h-3 w-28 rounded flex-shrink-0"
    style={{
      background: `linear-gradient(to right,
        rgba(251,191,36,0.05),
        rgba(251,191,36,0.85))`
    }}
  />
  <span className="text-xs text-muted-foreground
                   flex-shrink-0">
    High influence
  </span>
</div>
    </div>
  );
}

// ─── Interpretability report tab content ─────────────────────────────────────

export function InterpretabilityTabContent({
  result,
}: {
  result: TextXaiAuditResponse;
}) {
  const report = result.interpretability_report.trim();

  // Split the report into paragraphs for readable display.
  // The backend may return a single block; we still render it cleanly.
  const paragraphs = report
    .split(/\n{2,}/)
    .map((p) => p.trim())
    .filter(Boolean);

  return (
    <div className="space-y-4">
      <div className="space-y-1">
        <h3 className="text-sm font-semibold">Interpretability Report</h3>
        <p className="text-xs text-muted-foreground">
          Model-generated narrative explaining the factors behind the
          classification decision.
        </p>
      </div>

<div className="rounded-lg border bg-muted/30 px-5 py-4 space-y-3">
  {paragraphs.map((para, i) => (
    <p
      key={i}
      className="text-sm leading-relaxed text-foreground/90"
    >
      {para.split(/\*\*(.*?)\*\*/g).map((part, j) =>
        j % 2 === 1 ? (
          <strong key={j} className="font-semibold text-foreground">
            {part}
          </strong>
        ) : (
          <span key={j}>{part}</span>
        )
      )}
    </p>
  ))}
</div>

      <div className="flex items-center gap-1.5 text-xs text-muted-foreground">
        <FileText className="h-3.5 w-3.5" aria-hidden />
        <span>Report generated by {result.model_version}</span>
      </div>
    </div>
  );
}
